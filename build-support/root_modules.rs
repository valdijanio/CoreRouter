// Shared by the `build.rs` of the crates whose root module list is generated
// (engine, model, mcp): `include!`d, not a crate.
//
// Writes `$OUT_DIR/modules.rs` with `pub mod <name>;` for every `src/<name>.rs`
// and `src/<name>/mod.rs` (but `lib.rs` and `main.rs`), sorted. `lib.rs`
// includes it: a new module is a new file, no line in a shared list. The hand
// list made every pair of parallel PRs that added a module conflict (7 of 7
// pairs in the 7-agent round of 2026-10-22, docs/perf.md). A module that
// wants an attribute (`doc(hidden)`, `cfg`) says so inside: `#![doc(hidden)]`.

fn root_modules() -> Result<(), Box<dyn std::error::Error>> {
    use std::fmt::Write as _;
    let manifest = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let src = manifest.join("src");
    println!("cargo:rerun-if-changed=src");
    let mut mods: Vec<(String, std::path::PathBuf)> = Vec::new();
    for entry in std::fs::read_dir(&src)? {
        let path = entry?.path();
        let Some(file) = path.file_name().and_then(|f| f.to_str()).map(str::to_owned) else {
            continue;
        };
        let (name, target) = if path.is_dir() {
            let m = path.join("mod.rs");
            if !m.is_file() {
                continue;
            }
            (file, m)
        } else if let Some(stem) = file.strip_suffix(".rs") {
            if stem == "lib" || stem == "main" {
                continue;
            }
            (stem.to_owned(), path.clone())
        } else {
            continue;
        };
        if !name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
        {
            return Err(format!("src/{name}: module names are snake_case").into());
        }
        mods.push((name, target));
    }
    mods.sort();
    let mut out = String::from("// @generated by build-support/root_modules.rs from src/\n");
    for (name, path) in &mods {
        let path = path.to_str().ok_or("non-UTF-8 path")?.replace('\\', "/");
        writeln!(out, "#[path = {path:?}]\npub mod {name};")?;
    }
    let dest = std::path::PathBuf::from(std::env::var("OUT_DIR")?).join("modules.rs");
    std::fs::write(dest, out)?;
    Ok(())
}
