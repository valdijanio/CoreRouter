//! Generates the daemon's service list that `src/service/mod.rs` includes:
//! every `src/service/*.rs` (but `mod.rs`) becomes a module, and the ones
//! defining `pub(crate) const SERVICE` are started, in file-name order. A new service is a new
//! file — no edit to `main.rs` (its module list, flags and start-up were the
//! place every feature that runs in the daemon conflicted; docs/perf.md).

use std::error::Error;
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() -> Result<(), Box<dyn Error>> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let dir = manifest.join("src").join("service");
    println!("cargo:rerun-if-changed=src/service");
    let mut modules: Vec<(String, PathBuf, bool)> = Vec::new();
    for entry in std::fs::read_dir(&dir)? {
        let path = entry?.path();
        let Some(name) = path
            .file_name()
            .and_then(|f| f.to_str())
            .and_then(|f| f.strip_suffix(".rs"))
            .map(str::to_owned)
        else {
            continue;
        };
        if name == "mod" || !path.is_file() {
            continue;
        }
        if !name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
        {
            return Err(format!("src/service/{name}.rs: module names are snake_case").into());
        }
        let service = std::fs::read_to_string(&path)?.contains("pub(crate) const SERVICE:");
        modules.push((name, path, service));
    }
    modules.sort();
    let mut out =
        String::from("// @generated by apps/corerouter-daemon/build.rs from src/service/*.rs\n");
    for (name, path, _) in &modules {
        let path = path.to_str().ok_or("non-UTF-8 path")?.replace('\\', "/");
        writeln!(out, "#[path = {path:?}]\npub(crate) mod {name};")?;
    }
    out.push_str(
        "\n/// Every service, in file-name order.\npub(crate) const ALL: &[&Service] = &[\n",
    );
    for (name, _, service) in &modules {
        if *service {
            writeln!(out, "    &{name}::SERVICE,")?;
        }
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR")?).join("services.rs");
    std::fs::write(dest, out)?;
    Ok(())
}
