const NONE: egui::Modifiers = egui::Modifiers::NONE;

impl Harness {
    /// The Firewall window over a lab whose filter table holds `rules`.
    fn fw_with(rules: &[Value]) -> Self {
        let mut h = Self::new();
        for p in rules {
            h.exec("ip.firewall.filter.add", p.clone());
        }
        h.app.open.clear();
        h.app.open(Win::Firewall);
        h.reload_now();
        h
    }

    fn exec(&self, id: &str, p: Value) -> Value {
        lock(&self.session)
            .execute(id, &p)
            .unwrap_or_else(|e| panic!("{id} {p}: {e}"))
    }

    fn reload_now(&mut self) {
        self.app.cache.refreshed_at = None;
        self.idle();
        self.idle();
    }

    /// The UI posing as an operator connected over the control channel from
    /// 127.0.0.1 (interface `lo`), so the engine's lockout check applies.
    fn remote() -> Self {
        let session = shared(Session::virtual_lab());
        let caller = Caller::new(9, "tcp 127.0.0.1:40000")
            .with_principal(Principal::Local)
            .with_link(Link {
                peer: "127.0.0.1:40000".parse().unwrap(),
                local: "127.0.0.1:7979".parse().unwrap(),
            });
        let mut h = Self {
            ctx: egui::Context::default(),
            app: CoreRouterUi::with_backend(Box::new(Local::as_caller(session.clone(), caller))),
            session,
            time: 0.0,
            screen: egui::vec2(1400.0, 900.0),
            shapes: Vec::new(),
        };
        for _ in 0..3 {
            h.idle();
        }
        h
    }

    fn filter_len(&self) -> usize {
        self.exec("ip.firewall.filter.list", Value::Null)
            .as_array()
            .map_or(0, Vec::len)
    }

    /// Click the text field of `param` in the first firewall dialog and type.
    fn fill(&mut self, param: &str, text: &str) {
        self.idle();
        let win = interfaces::dialog_id(self.app.fw.dialogs[0].id);
        let at = self
            .ctx
            .read_response(dialog::field_id(win, param))
            .unwrap_or_else(|| panic!("no field {param}"))
            .rect
            .center();
        self.click(at);
        self.type_text(text);
    }
}

#[test]
fn rows_describe_rules_in_portuguese_and_warn_about_shadows() {
    let h = Harness::fw_with(&[
        json!({"chain": "input", "action": "drop", "src_address": "10.0.0.0/8"}),
        json!({"chain": "input", "src_address": "10.1.2.3"}),
    ]);
    assert!(h.has_text("Descarta pacotes para o roteador, vindos de 10.0.0.0/8."));
    let warning = "NUNCA CASA: a regra #0 acima já decide estes pacotes. \
                   Aceita pacotes para o roteador, vindos de 10.1.2.3.";
    assert!(h.has_text(warning), "the warning names the row by its #");
    assert!(h.has_text("S"), "flag S");
    let v = h.ctx.global_style().visuals.clone();
    assert_eq!(h.text_color(warning), v.warn_fg_color, "shadowed rows warn");
    assert_eq!(
        Some(h.text_color("Descarta pacotes para o roteador, vindos de 10.0.0.0/8.")),
        firewall::action_color("drop", v.dark_mode)
    );
}

#[test]
fn generated_zone_rules_grey_out_hand_edits() {
    let mut h = Harness::fw_with(&[]);
    h.exec(
        "ip.firewall.zone.set",
        json!({"from": "LAN", "to": "router", "action": "allow"}),
    );
    h.reload_now();
    let before = h.filter_len();
    let generated = "*2";
    h.click(h.fw_row(FwTable::Filter, generated));
    let remove = h
        .fw_tool(FwTable::Filter, table::Icon::Remove)
        .rect
        .center();
    h.click(remove);
    h.key(Key::Delete, NONE);
    assert_eq!(h.filter_len(), before, "nothing removed");
    h.tooltip_at(remove);
    assert!(
        h.has_text_containing("Generated by the zone matrix"),
        "the reason is on the greyed button"
    );
}

#[test]
fn assistants_write_rules_and_keep_errors_in_their_window() {
    let mut h = Harness::fw_with(&[]);
    h.app.open_wizard(Wizard::PortForward);
    h.idle();
    h.idle();
    assert!(h.has_text("Port Forward"));
    assert!(h.has_text_containing("Redireciona conexões que chegam pela WAN"));
    h.fill("dst_port", "8080");
    h.fill("to_addresses", "192.168.88.20");
    h.fill("to_ports", "80");
    h.key(Key::Enter, NONE);
    assert!(
        h.app.fw.dialogs.is_empty(),
        "OK closes on success: {:?} {:?}",
        h.app.fw.dialogs.first().map(|d| d.status.error.clone()),
        h.app.log()
    );
    let nat = h.exec("ip.firewall.nat.list", Value::Null);
    assert_eq!(nat[0]["action"], "dst-nat");
    assert_eq!(nat[0]["to_ports"], "80");
    assert_eq!(h.filter_len(), 1, "the forward accept");

    // Missing address: the engine's error stays in the window.
    h.app.open_wizard(Wizard::Block);
    h.idle();
    h.idle();
    h.key(Key::Enter, NONE);
    let err = h.app.fw.dialogs[0].status.error.clone().unwrap_or_default();
    assert!(err.contains("address"), "{err}");
    h.fill("address", "198.51.100.0/24");
    h.key(Key::Enter, NONE);
    assert!(h.app.fw.dialogs.is_empty());
    assert_eq!(h.filter_len(), 3, "+ drop in input and forward");

    // Safe defaults with the LAN interfaces typed in.
    h.app.open_wizard(Wizard::Defaults);
    h.idle();
    h.idle();
    assert!(h.has_text_containing("configuração inicial segura"));
    h.fill("lan", "ether2,ether3");
    h.fill("wan", "ether1");
    h.key(Key::Enter, NONE);
    assert!(h.app.fw.dialogs.is_empty(), "{:?}", h.app.log());
    assert_eq!(h.filter_len(), 3 + 11);
}

#[test]
fn zones_tab_shows_and_changes_the_matrix_in_both_themes() {
    let mut h = Harness::fw_with(&[]);
    h.exec(
        "ip.firewall.zone.set",
        json!({"from": "LAN", "to": "router", "action": "allow"}),
    );
    h.exec(
        "ip.firewall.zone.set",
        json!({"from": "WAN", "to": "router", "action": "block"}),
    );
    h.app.fw.tab = firewall::Tab::Zones;
    h.reload_now();
    assert!(h.has_text("from \\ to"));
    assert!(h.has_text("2 cell(s), 5 generated rule(s)"));
    for theme in [egui::Theme::Light, egui::Theme::Dark] {
        h.ctx.set_theme(theme);
        h.idle();
        h.idle();
        let dark = h.ctx.global_style().visuals.dark_mode;
        assert_eq!(
            Some(h.text_color("allow")),
            firewall::action_color("accept", dark)
        );
        assert_eq!(
            Some(h.text_color("block")),
            firewall::action_color("drop", dark)
        );
    }
    // Open the LAN → router cell and pick "block".
    h.click(h.text("allow"));
    h.idle();
    h.click(h.text("block"));
    h.reload_now();
    let cells = h.exec("ip.firewall.zone.list", Value::Null)["cells"].clone();
    assert_eq!(
        cells,
        json!([
            {"from": "LAN", "to": "router", "action": "block"},
            {"from": "WAN", "to": "router", "action": "block"},
        ])
    );
}

/// WCAG contrast ratio of two colours.
fn contrast(a: egui::Color32, b: egui::Color32) -> f32 {
    let lum = |c: egui::Color32| {
        let ch = |v: u8| {
            let v = f32::from(v) / 255.0;
            if v <= 0.039_28 {
                v / 12.92
            } else {
                ((v + 0.055) / 1.055).powf(2.4)
            }
        };
        0.2126 * ch(c.r()) + 0.7152 * ch(c.g()) + 0.0722 * ch(c.b())
    };
    let (hi, lo) = {
        let (x, y) = (lum(a), lum(b));
        if x > y { (x, y) } else { (y, x) }
    };
    (hi + 0.05) / (lo + 0.05)
}

#[test]
fn action_colours_read_on_both_themes() {
    for v in [egui::Visuals::light(), egui::Visuals::dark()] {
        for (action, hue) in [
            ("accept", "green"),
            ("drop", "red"),
            ("reject", "red"),
            ("dst-nat", "blue"),
            ("masquerade", "blue"),
            ("mark-connection", "purple"),
        ] {
            let c = firewall::action_color(action, v.dark_mode).unwrap();
            let ratio = contrast(c, v.panel_fill);
            assert!(ratio >= 4.5, "{action} on {:?}: {ratio}", v.panel_fill);
            let ok = match hue {
                "green" => c.g() > c.r() && c.g() > c.b(),
                "red" => c.r() > c.g() && c.r() > c.b(),
                "blue" => c.b() > c.r() && c.b() > c.g(),
                _ => c.r() > c.g() && c.b() > c.g(),
            };
            assert!(ok, "{action} should look {hue}: {c:?}");
        }
        assert_eq!(firewall::action_color("log", v.dark_mode), None);
    }
}

#[test]
fn a_lockout_is_held_until_the_operator_decides() {
    let mut h = Harness::remote();
    let drop_lo = json!({"chain": "input", "action": "drop", "in_interface": "lo"});

    // Cancel: nothing changes.
    h.app.run("ip.firewall.filter.add", drop_lo.clone());
    h.idle();
    h.idle();
    assert!(h.has_text("This change would lock you out"));
    assert!(h.has_text_containing("would drop this connection"));
    assert_eq!(h.filter_len(), 0);
    h.click(h.text("Cancel"));
    h.idle();
    assert!(!h.has_text("This change would lock you out"));
    assert_eq!(h.filter_len(), 0);

    // Apply anyway: sent again with force.
    h.app.run("ip.firewall.filter.add", drop_lo.clone());
    h.idle();
    h.idle();
    h.click(h.text("Apply anyway"));
    h.idle();
    assert_eq!(h.filter_len(), 1);
    assert!(!lock(&h.session).in_safe_mode());
    h.exec("ip.firewall.filter.remove", json!({"id": "*1"}));

    // Safe Mode, then apply.
    h.app.run("ip.firewall.filter.add", drop_lo);
    h.idle();
    h.idle();
    h.click(h.text("Safe Mode, then apply"));
    h.idle();
    assert!(lock(&h.session).in_safe_mode());
    assert_eq!(h.filter_len(), 1);
}

#[test]
fn a_cancelled_lockout_lands_in_the_assistant_that_sent_it() {
    let mut h = Harness::remote();
    h.app.open(Win::Firewall);
    h.reload_now();
    h.app.open_wizard(Wizard::Block);
    h.idle();
    h.idle();
    h.fill("address", "127.0.0.1");
    h.key(Key::Enter, NONE);
    h.idle();
    assert!(h.has_text("This change would lock you out"));
    h.click(h.text("Cancel"));
    h.idle();
    let err = h.app.fw.dialogs[0].status.error.clone().unwrap_or_default();
    assert!(err.starts_with("lockout: "), "{err}");
    assert_eq!(h.filter_len(), 0);
}
