//! Generates the module registry `src/lib.rs` includes, so a new window or
//! test needs no edit to a shared list (`lib.rs` was the merge-conflict hot
//! spot):
//! - every `src/*.rs` and `src/<name>/mod.rs` not declared in `lib.rs` itself
//!   becomes a module;
//! - the ones defining `pub(crate) const PANEL` become panels (`panel.rs`);
//! - every `src/tests/*.rs` becomes a module of `lib.rs`'s `tests`.

use std::error::Error;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The modules in `dir`: `<name>.rs` files and, with `dirs`, `<name>/mod.rs`
/// (a module with submodules of its own, like `i18n/`).
fn rust_files(dir: &Path, dirs: bool) -> Result<Vec<(String, PathBuf)>, Box<dyn Error>> {
    let mut out = Vec::new();
    for entry in std::fs::read_dir(dir)? {
        let mut path = entry?.path();
        if dirs && path.join("mod.rs").is_file() {
            let name = path.file_name().and_then(|f| f.to_str()).map(str::to_owned);
            if let Some(name) = name {
                path = path.join("mod.rs");
                check_name(&name, &path)?;
                out.push((name, path));
            }
            continue;
        }
        let Some(name) = path
            .file_name()
            .and_then(|f| f.to_str())
            .and_then(|f| f.strip_suffix(".rs"))
            .map(str::to_owned)
        else {
            continue;
        };
        if !path.is_file() {
            continue;
        }
        check_name(&name, &path)?;
        out.push((name, path));
    }
    out.sort();
    Ok(out)
}

fn check_name(name: &str, path: &Path) -> Result<(), Box<dyn Error>> {
    if name
        .bytes()
        .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
    {
        Ok(())
    } else {
        Err(format!("{}: module names are snake_case", path.display()).into())
    }
}

fn path_text(p: &Path) -> Result<String, Box<dyn Error>> {
    Ok(p.to_str().ok_or("non-UTF-8 path")?.replace('\\', "/"))
}

fn main() -> Result<(), Box<dyn Error>> {
    let src = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?).join("src");
    // Absolute: the generated `#[path]`s are absolute, and worktrees that
    // share a target directory must not reuse another worktree's list.
    println!("cargo:rerun-if-changed={}", src.display());
    let lib = std::fs::read_to_string(src.join("lib.rs"))?;
    // Only top-level declarations (`mod tests { mod x; }` lines are indented).
    let declared = |name: &str| {
        lib.lines()
            .any(|l| l == format!("mod {name};") || l == format!("pub mod {name};"))
    };
    let mut modules = String::from("// @generated by crates/ui/build.rs from src/*.rs\n");
    let mut panels = Vec::new();
    for (name, path) in rust_files(&src, true)? {
        if name == "lib" || declared(&name) {
            continue;
        }
        writeln!(modules, "#[path = \"{}\"]\nmod {name};", path_text(&path)?)?;
        let text = std::fs::read_to_string(&path)?;
        if text
            .lines()
            .any(|l| l.starts_with("pub(crate) const PANEL: "))
        {
            panels.push(name);
        }
    }
    modules.push_str("\npub(crate) static PANELS: &[&crate::panel::Panel] = &[\n");
    for p in &panels {
        writeln!(modules, "    &{p}::PANEL,")?;
    }
    modules.push_str("];\n");
    let mut tests = String::from("// @generated by crates/ui/build.rs from src/tests/*.rs\n");
    for (name, path) in rust_files(&src.join("tests"), false)? {
        writeln!(tests, "#[path = \"{}\"]\nmod {name};", path_text(&path)?)?;
    }
    let out = PathBuf::from(std::env::var("OUT_DIR")?);
    std::fs::write(out.join("ui_modules.rs"), modules)?;
    std::fs::write(out.join("ui_tests.rs"), tests)?;
    Ok(())
}
