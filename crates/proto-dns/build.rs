//! Generates the forwarder's stage list that `src/server/mod.rs` includes:
//! every `src/server/stage/*.rs` becomes a module, and the ones defining
//! `pub(crate) const STAGE: Stage` join the chain (ordered by their
//! `order`, not by file name). A new stage is a new file — no shared list
//! to edit, so the DNS parts built in parallel (statistics, adlist, zones)
//! do not conflict.

use std::error::Error;
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() -> Result<(), Box<dyn Error>> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let dir = manifest.join("src").join("server").join("stage");
    // Absolute: the generated `#[path]`s are absolute, and worktrees that
    // share a target directory must not reuse another worktree's list.
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut modules: Vec<(String, PathBuf, bool)> = Vec::new();
    for entry in std::fs::read_dir(&dir)? {
        let path = entry?.path();
        let Some(name) = path
            .file_name()
            .and_then(|f| f.to_str())
            .and_then(|f| f.strip_suffix(".rs"))
            .map(str::to_owned)
        else {
            continue;
        };
        if !path.is_file() {
            continue;
        }
        if !name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
        {
            return Err(format!("src/server/stage/{name}.rs: module names are snake_case").into());
        }
        let stage = std::fs::read_to_string(&path)?.contains("pub(crate) const STAGE: Stage");
        modules.push((name, path, stage));
    }
    modules.sort();
    let mut out =
        String::from("// @generated by crates/proto-dns/build.rs from src/server/stage/*.rs\n");
    for (name, path, _) in &modules {
        let path = path.to_str().ok_or("non-UTF-8 path")?.replace('\\', "/");
        writeln!(out, "#[path = {path:?}]\npub(crate) mod {name};")?;
    }
    out.push_str("\n/// Every stage, in file-name order (`stages()` sorts them).\nstatic FOUND: &[&Stage] = &[\n");
    for (name, _, stage) in &modules {
        if *stage {
            writeln!(out, "    &{name}::STAGE,")?;
        }
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR")?).join("stages.rs");
    std::fs::write(dest, out)?;
    Ok(())
}
