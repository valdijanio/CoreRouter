//! Generates the command-area registry that `src/cmd/mod.rs` includes: every
//! `src/cmd/*.rs` (but `mod.rs`) becomes a module, and the ones defining
//! `COMMANDS` become areas, in file-name order. A new area is a new file —
//! no shared list to edit (`cmd/mod.rs` was a merge-conflict hot spot).

use std::error::Error;
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() -> Result<(), Box<dyn Error>> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let dir = manifest.join("src").join("cmd");
    println!("cargo:rerun-if-changed=src/cmd");
    let mut modules: Vec<(String, PathBuf, bool)> = Vec::new();
    for entry in std::fs::read_dir(&dir)? {
        let path = entry?.path();
        let Some(name) = path
            .file_name()
            .and_then(|f| f.to_str())
            .and_then(|f| f.strip_suffix(".rs"))
            .map(str::to_owned)
        else {
            continue;
        };
        if name == "mod" || !path.is_file() {
            continue;
        }
        if !name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
        {
            return Err(format!("src/cmd/{name}.rs: module names are snake_case").into());
        }
        let area = std::fs::read_to_string(&path)?.contains("const COMMANDS: &[CommandSpec]");
        modules.push((name, path, area));
    }
    modules.sort();
    let mut out = String::from("// @generated by crates/engine/build.rs from src/cmd/*.rs\n");
    for (name, path, _) in &modules {
        let path = path.to_str().ok_or("non-UTF-8 path")?.replace('\\', "/");
        writeln!(out, "#[path = \"{path}\"]\npub(crate) mod {name};")?;
    }
    out.push_str("\nstatic AREAS: &[&[CommandSpec]] = &[\n");
    for (name, _, area) in &modules {
        if *area {
            writeln!(out, "    {name}::COMMANDS,")?;
        }
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR")?).join("cmd_areas.rs");
    std::fs::write(dest, out)?;
    Ok(())
}
